import type { LucideIcon } from "lucide-react";

/** Icons referenced by insight strings coming out of the report engine. */
export const INSIGHT_ICONS: Record<string, LucideIcon> = {
  eye: Eye,
  activity: Activity,
  hand: Hand,
  mic: Mic,
  smile: Smile,
  crown: Crown,
  quote: Quote,
  gauge: Gauge,
  sparkles: Sparkles,
};

export function InsightIcon({ name, className }: { name: string; className?: string }) {
  const Icon = INSIGHT_ICONS[name] ?? Sparkles;
  return <Icon className={className} aria-hidden />;
}

